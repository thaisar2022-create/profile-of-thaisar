export function getTranslation(lang: Language, section: keyof typeof translations, key: string): string {
  const sec = translations[section] as Record<string, string>;
  const fullKey = `${key}${lang === 'my' ? 'My' : 'En'}`;
  return sec[fullKey] || sec[`${key}My`] || key;
}
